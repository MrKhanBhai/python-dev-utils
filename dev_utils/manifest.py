"""Portable JSON manifests for verifying directory contents."""
from __future__ import annotations

import json
from pathlib import Path, PurePosixPath
from typing import Any

from .checksum import PathLike, _new_hash
from .directory_hash import directory_hashes

MANIFEST_VERSION = 1


def _validate_excluded_dirs(excluded_dirs: Any) -> list[str]:
    if not isinstance(excluded_dirs, list) or any(
        not isinstance(name, str) or not name for name in excluded_dirs
    ):
        raise ValueError("manifest excluded_dirs must be a list of non-empty strings")
    if len(set(excluded_dirs)) != len(excluded_dirs):
        raise ValueError("manifest excluded_dirs must not contain duplicates")
    return excluded_dirs


def build_manifest(
    directory: PathLike,
    algorithm: str = "sha256",
    exclude_dirs: tuple[str, ...] = (),
) -> dict[str, Any]:
    """Build a versioned, deterministic manifest of files below a directory."""
    excluded = list(exclude_dirs)
    files = directory_hashes(
        directory, algorithm=algorithm, exclude_dirs=tuple(excluded)
    )
    return {
        "manifest_version": MANIFEST_VERSION,
        "algorithm": algorithm,
        "exclude_dirs": excluded,
        "files": files,
    }


def write_manifest(
    directory: PathLike,
    manifest_path: PathLike,
    algorithm: str = "sha256",
    exclude_dirs: tuple[str, ...] = (),
) -> dict[str, Any]:
    """Write a UTF-8 JSON manifest and return the manifest data."""
    manifest = build_manifest(directory, algorithm, exclude_dirs)
    destination = Path(manifest_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    destination.write_text(serialized, encoding="utf-8")
    return manifest


def _validate_manifest_data(data: dict[str, Any]) -> None:
    if data.get("manifest_version") != MANIFEST_VERSION:
        raise ValueError("unsupported manifest version")
    algorithm = data.get("algorithm")
    if not isinstance(algorithm, str):
        raise ValueError("manifest algorithm must be a string")
    digest_size = _new_hash(algorithm).digest_size * 2
    excluded_dirs = data.get("exclude_dirs", [])
    _validate_excluded_dirs(excluded_dirs)
    files = data.get("files")
    if not isinstance(files, dict):
        raise ValueError("manifest files must be a JSON object")
    for relative, digest in files.items():
        if not isinstance(relative, str) or not isinstance(digest, str):
            raise ValueError("manifest paths and digests must be strings")
        path = PurePosixPath(relative)
        if (
            not relative
            or relative in {".", ".."}
            or path.is_absolute()
            or ".." in path.parts
            or "\\" in relative
        ):
            raise ValueError(f"unsafe manifest path: {relative!r}")
        if len(digest) != digest_size:
            raise ValueError(f"invalid digest length for {relative!r}")
        try:
            int(digest, 16)
        except ValueError as exc:
            raise ValueError(
                f"invalid hexadecimal digest for {relative!r}"
            ) from exc


def load_manifest(manifest_path: PathLike) -> dict[str, Any]:
    """Load and validate a manifest generated by write_manifest."""
    data = json.loads(Path(manifest_path).read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError("manifest must be a JSON object")
    _validate_manifest_data(data)
    data.setdefault("exclude_dirs", [])
    return data


def verify_manifest(
    directory: PathLike,
    manifest: dict[str, Any] | PathLike,
    include_untracked: bool = True,
) -> dict[str, list[str]]:
    """Compare a directory with a manifest without modifying files.

    Returns sorted missing, modified and untracked relative paths.
    Pass validated manifest data or a path to a JSON manifest.
    """
    expected = (
        load_manifest(manifest)
        if isinstance(manifest, (str, Path))
        else manifest
    )
    if not isinstance(expected, dict):
        raise TypeError("manifest must be a mapping or a manifest path")
    _validate_manifest_data(expected)
    root = Path(directory)
    if not root.is_dir():
        raise NotADirectoryError(str(root))
    actual = directory_hashes(
        root,
        algorithm=expected["algorithm"],
        exclude_dirs=tuple(expected.get("exclude_dirs", [])),
    )
    expected_files = expected["files"]
    missing = sorted(set(expected_files) - set(actual))
    common = set(expected_files) & set(actual)
    modified = sorted(
        path for path in common if expected_files[path] != actual[path]
    )
    untracked = sorted(set(actual) - set(expected_files)) if include_untracked else []
    return {"missing": missing, "modified": modified, "untracked": untracked}
